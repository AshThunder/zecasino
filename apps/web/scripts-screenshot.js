const { chromium } = require("playwright-core");
const O = "/workspace/zcasino/screenshots", B = "http://localhost:3100";
(async () => {
  const br = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
  const d = await br.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 }); d.on("response", r => r.status() >= 400 && console.log("HTTP", r.status(), r.url())); d.on("console", m => m.type()==="error" && console.log("ERR", m.text())); d.on("pageerror", e => console.log("PAGEERR", e.message));
  await d.goto(B + "/", { waitUntil: "networkidle" }); await d.waitForTimeout(1500);
  await d.screenshot({ path: `${O}/01-lobby.png` });
  await d.screenshot({ path: `${O}/02-lobby-full.png`, fullPage: true });
  await d.click("text=Cashier"); await d.waitForTimeout(800);
  await d.screenshot({ path: `${O}/03-cashier-deposit.png` });
  await d.click("role=tab[name='Withdraw']"); await d.waitForTimeout(400);
  await d.screenshot({ path: `${O}/04-cashier-withdraw.png` });
  await d.goto(B + "/table/roulette", { waitUntil: "networkidle" }); await d.waitForTimeout(800);
  await d.screenshot({ path: `${O}/05-roulette.png` });
  await d.click("text=Spin"); await d.waitForTimeout(2500);
  await d.screenshot({ path: `${O}/06-roulette-spinning.png` });
  await d.waitForTimeout(5000);
  await d.screenshot({ path: `${O}/07-roulette-result.png` });
  await d.goto(B + "/table/carrot", { waitUntil: "networkidle" }); await d.waitForTimeout(1200);
  await d.screenshot({ path: `${O}/08-carrot.png` });
  await d.click("text=Peek inside"); await d.waitForTimeout(1100);
  await d.screenshot({ path: `${O}/09-carrot-peek.png` });
  await d.waitForTimeout(2200);
  await d.click("text=I've got the carrot."); await d.waitForTimeout(5200);
  await d.screenshot({ path: `${O}/10-carrot-reveal.png` });
  const m = await br.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true });
  await m.goto(B + "/", { waitUntil: "networkidle" }); await m.waitForTimeout(1500);
  await m.screenshot({ path: `${O}/11-mobile-lobby.png` });
  await br.close();
})();
